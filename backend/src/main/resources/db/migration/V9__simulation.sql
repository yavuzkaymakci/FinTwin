-- V9: macro scenarios, simulation runs and per-customer cash-flow forecasts (simulation engine, step 5).

CREATE SCHEMA IF NOT EXISTS simulation;

-- A macro scenario. `parameters` is the ScenarioParameters JSON (camelCase) validated by the backend
-- (Bean Validation) and the ML service (Pydantic); presets are seeded below and cannot be edited.
CREATE TABLE simulation.scenario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    description TEXT         NOT NULL,
    parameters  JSONB        NOT NULL,
    preset      BOOLEAN      NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- One simulation run of a scenario (optionally against a baseline scenario with common random numbers).
CREATE TABLE simulation.simulation_run (
    id                   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    scenario_id          BIGINT           NOT NULL REFERENCES simulation.scenario (id),
    baseline_scenario_id BIGINT REFERENCES simulation.scenario (id),
    -- Twin state the run starts from: NULL = current state, otherwise a month-start snapshot date.
    start_date           DATE,
    -- Parameters and assumptions as sent to the ML service (scenarios can change later; runs stay reproducible).
    parameters           JSONB            NOT NULL,
    baseline_parameters  JSONB,
    assumptions          JSONB,
    status               VARCHAR(16)      NOT NULL
        CHECK (status IN ('PENDING', 'QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    progress             DOUBLE PRECISION NOT NULL DEFAULT 0,
    ml_job_id            VARCHAR(64),
    requested_at         TIMESTAMPTZ      NOT NULL DEFAULT now(),
    started_at           TIMESTAMPTZ,
    finished_at          TIMESTAMPTZ,
    error                TEXT,
    -- Portfolio, segment, migration and top-customer results (everything except the per-customer forecasts).
    result               JSONB,
    duration_seconds     DOUBLE PRECISION,
    peak_rss_mb          DOUBLE PRECISION
);

CREATE INDEX idx_simulation_run_status ON simulation.simulation_run (status);
CREATE INDEX idx_simulation_run_scenario ON simulation.simulation_run (scenario_id, requested_at DESC);

-- Monthly P10/P50/P90 bands of balances and liquidity buffer per customer and run (fan chart data).
CREATE TABLE simulation.customer_forecast (
    run_id      BIGINT NOT NULL REFERENCES simulation.simulation_run (id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL,
    forecast    JSONB  NOT NULL,
    PRIMARY KEY (run_id, customer_id)
);

CREATE INDEX idx_customer_forecast_customer ON simulation.customer_forecast (customer_id, run_id DESC);

