/**
 * Builds the post-generation statistics report (markdown) from the database and writes it into the marked section
 * of {@code docs/data-generation.md}.
 */
@Service
public class GenerationReportService {

    public static final String START_MARKER = "<!-- generation-report:start -->";
    public static final String END_MARKER = "<!-- generation-report:end -->";

    private static final Logger log = LoggerFactory.getLogger(GenerationReportService.class);
    private static final String LOCAL_TIME = "(t.occurred_at AT TIME ZONE 'Europe/Istanbul')";

    private final JdbcTemplate jdbc;

    public GenerationReportService(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    public String buildReport(GenerationResult result) {
        GeneratorProperties p = result.properties();
        StringBuilder md = new StringBuilder();
        md.append("_Generated by the `generate` profile; do not edit this section by hand._\n\n");
        md.append("### Run\n\n");
        md.append(table(List.of("Parameter", "Value"), List.of(
                List.of("Customers", fmt(p.customerCount())),
                List.of("Months", p.months() + " (" + p.startMonth() + " .. " + p.endMonth() + ")"),
                List.of("Seed", String.valueOf(p.seed())),
                List.of("Total rows", fmt(result.totalRows())),
                List.of("Wall-clock time", seconds(result.total().toMillis())),
                List.of("Simulation time (parallel, overlapped)", seconds(result.simulation().toMillis())),
                List.of("Database write time (summed over writer threads)", seconds(result.writing().toMillis())),
                List.of("Throughput", fmt(Math.round(result.totalRows()
                        / Math.max(result.total().toMillis() / 1000.0, 0.001))) + " rows/s"))));

        md.append("\n### Row counts\n\n");
        md.append(table(List.of("Table", "Rows"), result.rowCounts().entrySet().stream()
                .map(e -> List.of("`" + e.getKey() + "`", fmt(e.getValue()))).toList()));

        md.append("\n### Outcome rates\n\n");
        md.append(outcomes());

        md.append("\n### Segments\n\n");
        md.append(segments());

        md.append("\n### Default and churn by financial stress decile\n\n");
        md.append(stressDeciles(p));

        md.append("\n### Monthly transaction volume and hidden state\n\n");
        md.append(monthly());

        md.append("\n### Category distribution (ground-truth labels)\n\n");
        md.append(categories());

        md.append("\n### Channels and installments\n\n");
        md.append(channels());

        md.append("\n### Card repayment behaviour\n\n");
        md.append(cardBehaviour());

        md.append("\n### Calendar effects (average purchases per day)\n\n");
        md.append(calendarEffects());

        md.append("\n### Sample raw descriptions\n\n");
        md.append(samples());
        return md.toString();
    }

    /** Replaces the marked report section of {@code path} (creating the file or markers if missing). */
    public void writeReport(Path path, String report) {
        try {
            String section = START_MARKER + "\n" + report + END_MARKER;
            String content = Files.exists(path) ? Files.readString(path, StandardCharsets.UTF_8) : "";
            int start = content.indexOf(START_MARKER);
            int end = content.indexOf(END_MARKER);
            String updated = start >= 0 && end > start
                    ? content.substring(0, start) + section + content.substring(end + END_MARKER.length())
                    : content + (content.isEmpty() ? "" : "\n\n") + "## Generation report\n\n" + section + "\n";
            if (path.getParent() != null) {
                Files.createDirectories(path.getParent());
            }
            Files.writeString(path, updated, StandardCharsets.UTF_8);
            log.info("Report written to {}", path.toAbsolutePath().normalize());
        } catch (IOException e) {
            throw new UncheckedIOException("Could not write report to " + path, e);
        }
    }

    private String outcomes() {
        Map<String, Object> o = jdbc.queryForMap("""
                SELECT COUNT(*) AS customers,
                       AVG(o.defaulted::int) AS default_rate,
                       AVG(o.churned::int) AS churn_rate,
                       AVG((o.late_payment_count > 0)::int) AS late_rate,
                       AVG(o.defaulted::int) FILTER (WHERE x.has_credit) AS default_rate_credit,
                       COUNT(*) FILTER (WHERE x.has_credit) AS credit_customers,
                       AVG((o.unemployment_months > 0)::int) AS unemployment_rate
                FROM ground_truth.customer_outcome o
                JOIN LATERAL (
                    SELECT EXISTS (SELECT 1 FROM account a WHERE a.customer_id = o.customer_id
                                   AND a.account_type = 'CREDIT_CARD')
                        OR EXISTS (SELECT 1 FROM loan l WHERE l.customer_id = o.customer_id) AS has_credit
                ) x ON TRUE""");
        Map<String, Long> events = new LinkedHashMap<>();
        jdbc.query("SELECT event_type, COUNT(*) FROM customer_event GROUP BY event_type ORDER BY event_type",
                rs -> {
                    events.put(rs.getString(1), rs.getLong(2));
                });
        List<List<String>> rows = new ArrayList<>();
        rows.add(List.of("Customers", fmt(num(o.get("customers")).longValue())));
        rows.add(List.of("Customers with credit exposure (card or loan)",
                fmt(num(o.get("credit_customers")).longValue())));
        rows.add(List.of("Default rate (DEFAULT = 90+ DPD), all customers", pct(o.get("default_rate"))));
        rows.add(List.of("Default rate, customers with credit exposure", pct(o.get("default_rate_credit"))));
        rows.add(List.of("Churn rate", pct(o.get("churn_rate"))));
        rows.add(List.of("Customers with at least one late payment", pct(o.get("late_rate"))));
        rows.add(List.of("Customers with an unemployment / income shock spell", pct(o.get("unemployment_rate"))));
        events.forEach((type, n) -> rows.add(List.of("`" + type + "` events", fmt(n))));
        return table(List.of("Metric", "Value"), rows);
    }

    private String segments() {
        List<List<String>> rows = jdbc.query("""
                SELECT c.segment,
                       COUNT(*) AS customers,
                       percentile_cont(0.5) WITHIN GROUP (ORDER BY l.base_monthly_income) AS base_income,
                       percentile_cont(0.5) WITHIN GROUP (ORDER BY c.monthly_net_income) AS latest_income,
                       MIN(l.base_monthly_income) AS min_income,
                       MAX(l.base_monthly_income) AS max_income,
                       AVG((EXISTS (SELECT 1 FROM account a WHERE a.customer_id = c.id
                                    AND a.account_type = 'CREDIT_CARD'))::int) AS card_share,
                       AVG((EXISTS (SELECT 1 FROM loan x WHERE x.customer_id = c.id))::int) AS loan_share,
                       AVG(o.mean_stress) AS mean_stress,
                       AVG(o.defaulted::int) AS default_rate,
                       AVG(o.churned::int) AS churn_rate,
                       AVG((o.late_payment_count > 0)::int) AS late_rate
                FROM customer c
                JOIN ground_truth.customer_latent l ON l.customer_id = c.id
                JOIN ground_truth.customer_outcome o ON o.customer_id = c.id
                GROUP BY c.segment
                ORDER BY COUNT(*) DESC""", (rs, i) -> List.of(
                rs.getString("segment"),
                fmt(rs.getLong("customers")),
                money(rs.getDouble("base_income")),
                money(rs.getDouble("latest_income")),
                money(rs.getDouble("min_income")) + " – " + money(rs.getDouble("max_income")),
                pct(rs.getDouble("card_share")),
                pct(rs.getDouble("loan_share")),
                String.format(Locale.ROOT, "%.3f", rs.getDouble("mean_stress")),
                pct(rs.getDouble("late_rate")),
                pct(rs.getDouble("default_rate")),
                pct(rs.getDouble("churn_rate"))));
        long total = rows.stream().mapToLong(r -> Long.parseLong(r.get(1).replace(",", ""))).sum();
        List<List<String>> withShare = rows.stream().map(r -> {
            List<String> copy = new ArrayList<>(r);
            copy.add(2, pct((double) Long.parseLong(r.get(1).replace(",", "")) / total));
            return copy;
        }).toList();
        return table(List.of("Segment", "Customers", "Share", "Median base income", "Median latest income",
                "Base income range", "Has card", "Has loan", "Mean stress", "≥1 late", "Default", "Churn"), withShare);
    }

    private String stressDeciles(GeneratorProperties p) {
        YearMonth snapshot = p.months() >= 12 ? p.startMonth().plusMonths(5) : p.startMonth();
        LocalDate snapshotEnd = snapshot.atEndOfMonth();
        List<List<String>> rows = jdbc.query("""
                WITH snap AS (
                    SELECT s.customer_id, s.financial_stress,
                           ntile(10) OVER (ORDER BY s.financial_stress) AS decile
                    FROM ground_truth.customer_monthly_state s
                    WHERE s.period = ? AND s.days_past_due = 0
                )
                SELECT decile, COUNT(*) AS customers,
                       MIN(financial_stress) AS lo, MAX(financial_stress) AS hi,
                       AVG((o.defaulted AND o.default_date > ?)::int) AS default_rate,
                       AVG((o.churned AND o.churn_date > ?)::int) AS churn_rate,
                       AVG((EXISTS (SELECT 1 FROM customer_event e WHERE e.customer_id = snap.customer_id
                                    AND e.event_type = 'LATE_PAYMENT' AND e.event_date > ?))::int) AS late_rate
                FROM snap JOIN ground_truth.customer_outcome o USING (customer_id)
                GROUP BY decile ORDER BY decile""",
                (rs, i) -> List.of(
                        String.valueOf(rs.getInt("decile")),
                        fmt(rs.getLong("customers")),
                        String.format(Locale.ROOT, "%.3f – %.3f", rs.getDouble("lo"), rs.getDouble("hi")),
                        pct(rs.getDouble("late_rate")),
                        pct(rs.getDouble("default_rate")),
                        pct(rs.getDouble("churn_rate"))),
                Date.valueOf(snapshot.atDay(1)), Date.valueOf(snapshotEnd), Date.valueOf(snapshotEnd),
                Date.valueOf(snapshotEnd));
        return "Stress measured at the end of " + snapshot + " for customers that were current (0 DPD) at that "
                + "point; outcomes are events after the snapshot until the end of the horizon.\n\n"
                + table(List.of("Stress decile", "Customers", "Stress range", "Later late payment",
                "Later default", "Later churn"), rows);
    }

    private String monthly() {
        Map<String, List<String>> byMonth = new LinkedHashMap<>();
        jdbc.query("""
                SELECT to_char(date_trunc('month', %s), 'YYYY-MM') AS month,
                       COUNT(*) AS transactions,
                       COUNT(DISTINCT t.customer_id) AS active,
                       SUM(t.amount) FILTER (WHERE t.direction = 'DEBIT' AND t.currency = 'TRY'
                                              AND t.channel IN ('POS', 'ECOMMERCE')) AS purchases
                FROM bank_transaction t GROUP BY 1 ORDER BY 1""".formatted(LOCAL_TIME), rs -> {
            long tx = rs.getLong("transactions");
            long active = rs.getLong("active");
            byMonth.put(rs.getString("month"), new ArrayList<>(List.of(rs.getString("month"), fmt(tx), fmt(active),
                    String.format(Locale.ROOT, "%.1f", (double) tx / Math.max(active, 1)),
                    money(num(rs.getObject("purchases")).doubleValue() / 1_000_000) + " M")));
        });
        Map<String, double[]> cpi = new LinkedHashMap<>();
        jdbc.query("""
                SELECT to_char(period, 'YYYY-MM') AS month, value FROM macro_indicator
                WHERE indicator = 'MONTHLY_INFLATION' ORDER BY period""",
                rs -> {
                    cpi.put(rs.getString(1), new double[]{rs.getDouble(2)});
                });
        Map<String, double[]> state = new LinkedHashMap<>();
        jdbc.query("""
                SELECT to_char(period, 'YYYY-MM') AS month, AVG(financial_stress), AVG(monthly_income),
                       AVG((days_past_due >= 30)::int), AVG(card_utilization), AVG(real_income_loss)
                FROM ground_truth.customer_monthly_state GROUP BY 1 ORDER BY 1""",
                rs -> {
                    state.put(rs.getString(1), new double[]{rs.getDouble(2), rs.getDouble(3), rs.getDouble(4),
                            rs.getDouble(5), rs.getDouble(6)});
                });
        List<List<String>> rows = new ArrayList<>();
        for (Map.Entry<String, List<String>> e : byMonth.entrySet()) {
            List<String> row = e.getValue();
            double[] c = cpi.get(e.getKey());
            double[] s = state.get(e.getKey());
            row.add(c == null ? "" : String.format(Locale.ROOT, "%.2f%%", c[0]));
            row.add(s == null ? "" : money(s[1]));
            row.add(s == null ? "" : pct(s[4]));
            row.add(s == null ? "" : String.format(Locale.ROOT, "%.3f", s[0]));
            row.add(s == null ? "" : pct(s[3]));
            row.add(s == null ? "" : pct(s[2]));
            rows.add(row);
        }
        return table(List.of("Month", "Transactions", "Active customers", "Tx / customer", "Card+debit purchases (TRY)",
                "CPI m/m", "Avg income", "Avg real income loss", "Avg stress", "Avg card utilisation", "30+ DPD share"),
                rows);
    }

    private String categories() {
        List<Object[]> raw = jdbc.query("""
                SELECT tl.category_code, COUNT(*) AS n,
                       SUM(t.amount) FILTER (WHERE t.currency = 'TRY') AS total,
                       AVG(t.amount) FILTER (WHERE t.currency = 'TRY') AS avg
                FROM bank_transaction t JOIN ground_truth.transaction_label tl ON tl.transaction_id = t.id
                GROUP BY 1 ORDER BY n DESC""", (rs, i) -> new Object[]{rs.getString(1), rs.getLong(2),
                num(rs.getObject(3)).doubleValue(), num(rs.getObject(4)).doubleValue()});
        long total = raw.stream().mapToLong(r -> (long) r[1]).sum();
        return table(List.of("Category", "Transactions", "Share", "Volume (TRY)", "Avg amount (TRY)"),
                raw.stream().map(r -> List.of("`" + r[0] + "`", fmt((long) r[1]), pct((double) (long) r[1] / total),
                        money((double) r[2] / 1_000_000) + " M", money((double) r[3]))).toList());
    }

    private String channels() {
        List<List<String>> rows = jdbc.query("""
                SELECT channel, COUNT(*) AS n,
                       AVG((installment_count > 1)::int) AS installment_share
                FROM bank_transaction GROUP BY channel ORDER BY n DESC""", (rs, i) -> List.of(
                "`" + rs.getString(1) + "`", fmt(rs.getLong(2)), pct(rs.getDouble(3))));
        String installments = jdbc.query("""
                SELECT installment_count, COUNT(*) FROM bank_transaction
                WHERE installment_count > 1 GROUP BY 1 ORDER BY 1""",
                (rs, i) -> rs.getInt(1) + " → " + fmt(rs.getLong(2))).stream().collect(Collectors.joining(", "));
        return table(List.of("Channel", "Transactions", "With installments"), rows)
                + "\nInstallment counts: " + installments + "\n";
    }

    private String cardBehaviour() {
        Map<String, Object> m = jdbc.queryForMap("""
                SELECT COUNT(*) AS statements,
                       AVG((paid_amount >= statement_balance)::int) AS full,
                       AVG((paid_amount >= minimum_payment AND paid_amount < statement_balance)::int) AS partial,
                       AVG((paid_amount < minimum_payment)::int) AS below_min,
                       AVG(days_past_due) FILTER (WHERE days_past_due > 0) AS avg_dpd
                FROM card_statement""");
        return table(List.of("Metric", "Value"), List.of(
                List.of("Statements", fmt(num(m.get("statements")).longValue())),
                List.of("Paid in full", pct(m.get("full"))),
                List.of("Paid minimum or more (not full)", pct(m.get("partial"))),
                List.of("Paid less than minimum (late)", pct(m.get("below_min"))),
                List.of("Average DPD of late statements", String.format(Locale.ROOT, "%.1f days",
                        num(m.get("avg_dpd")).doubleValue()))));
    }

    private String calendarEffects() {
        List<String> categories = List.of("GROCERY", "RESTAURANT", "CLOTHING", "ECOMMERCE", "TRAVEL", "FUEL");
        String[] dayTypes = {"Weekday", "Weekend", "Pre-bayram week", "Bayram", "Black Friday week"};
        Map<String, double[]> sums = new LinkedHashMap<>();
        for (String c : categories) {
            sums.put(c, new double[dayTypes.length]);
        }
        Map<LocalDate, Map<String, Long>> byDay = new LinkedHashMap<>();
        jdbc.query("""
                SELECT %s::date AS d, tl.category_code, COUNT(*)
                FROM bank_transaction t JOIN ground_truth.transaction_label tl ON tl.transaction_id = t.id
                WHERE t.direction = 'DEBIT' AND t.channel IN ('POS', 'ECOMMERCE')
                GROUP BY 1, 2""".formatted(LOCAL_TIME), rs -> {
            byDay.computeIfAbsent(rs.getDate(1).toLocalDate(), k -> new LinkedHashMap<>())
                    .put(rs.getString(2), rs.getLong(3));
        });
        int[] dayCounts = new int[dayTypes.length];
        for (Map.Entry<LocalDate, Map<String, Long>> e : byDay.entrySet()) {
            LocalDate d = e.getKey();
            int type;
            if (TurkishCalendar.isReligiousHoliday(d)) {
                type = 3;
            } else if (TurkishCalendar.isPreHolidayShopping(d)) {
                type = 2;
            } else if (d.getMonthValue() == 11 && d.getDayOfMonth() >= 20) {
                type = 4;
            } else if (TurkishCalendar.isWeekend(d) || TurkishCalendar.isPublicHoliday(d)) {
                type = 1;
            } else {
                type = 0;
            }
            dayCounts[type]++;
            for (String c : categories) {
                sums.get(c)[type] += e.getValue().getOrDefault(c, 0L);
            }
        }
        List<List<String>> rows = new ArrayList<>();
        for (String c : categories) {
            List<String> row = new ArrayList<>();
            row.add("`" + c + "`");
            double weekday = dayCounts[0] == 0 ? 0 : sums.get(c)[0] / dayCounts[0];
            for (int t = 0; t < dayTypes.length; t++) {
                double avg = dayCounts[t] == 0 ? 0 : sums.get(c)[t] / dayCounts[t];
                row.add(t == 0 || weekday == 0 ? String.format(Locale.ROOT, "%.0f", avg)
                        : String.format(Locale.ROOT, "%.0f (×%.2f)", avg, avg / weekday));
            }
            rows.add(row);
        }
        List<String> header = new ArrayList<>();
        header.add("Category");
        for (int t = 0; t < dayTypes.length; t++) {
            header.add(dayTypes[t] + " (" + dayCounts[t] + " d)");
        }
        return table(header, rows);
    }

    private String samples() {
        Long max = jdbc.queryForObject("SELECT COALESCE(MAX(id), 0) FROM bank_transaction", Long.class);
        if (max == null || max == 0) {
            return "_No transactions._\n";
        }
        List<Long> ids = new ArrayList<>();
        for (int i = 1; i <= 16; i++) {
            ids.add(Math.max(1, max * i / 17));
        }
        String in = ids.stream().map(String::valueOf).collect(Collectors.joining(","));
        List<List<String>> rows = jdbc.query("""
                SELECT t.raw_description, tl.category_code, t.channel, t.amount, t.installment_count
                FROM bank_transaction t JOIN ground_truth.transaction_label tl ON tl.transaction_id = t.id
                WHERE t.id IN (%s) ORDER BY t.id""".formatted(in), (rs, i) -> List.of(
                "`" + rs.getString(1) + "`", "`" + rs.getString(2) + "`", rs.getString(3),
                money(rs.getBigDecimal(4).doubleValue()), String.valueOf(rs.getInt(5))));
        return table(List.of("raw_description", "True category", "Channel", "Amount", "Installments"), rows);
    }

    // ---------------------------------------------------------------- formatting

    static String table(List<String> header, List<List<String>> rows) {
        StringBuilder sb = new StringBuilder();
        sb.append("| ").append(String.join(" | ", header)).append(" |\n");
        sb.append("|").append("---|".repeat(header.size())).append("\n");
        for (List<String> row : rows) {
            sb.append("| ").append(String.join(" | ", row)).append(" |\n");
        }
        return sb.toString();
    }

    private static Number num(Object value) {
        if (value == null) {
            return 0;
        }
        return value instanceof Number n ? n : new BigDecimal(value.toString());
    }

    private static String pct(Object value) {
        return String.format(Locale.ROOT, "%.2f%%", num(value).doubleValue() * 100);
    }

    private static String fmt(long value) {
        return String.format(Locale.ROOT, "%,d", value);
    }

    private static String money(double value) {
        return String.format(Locale.ROOT, "%,.0f", value);
    }

    private static String seconds(long millis) {
        return String.format(Locale.ROOT, "%.1f s", millis / 1000.0);
    }
}
